"""全局配置：输出规格、声带源、女性化与人性化参数。

声带源方案（dsp.py 模块说明里有完整对比）：
    fm2    两算子 FM      y(t) = sin(2π·k·f0·t + I·sin(2π·f0·t))   —— 纲领 三.1 原式
    fm2s   两算子 FM + 谐波包络平滑
    fmfb   反馈 FM        y[n] = sin(φ[n] + β·y[n-1])              —— 已选定

实测「梳齿」（声源谱相对自身平滑包络的偏差，dB）：fm2 σ≈5.1 / fm2s σ≈1.9 / fmfb σ≈0.8
"""

# --------------------------------------------------------------------------
# 输出规格
# --------------------------------------------------------------------------
SR = 44100            # 采样率
BIT_DEPTH = 16        # 位深
CHANNELS = 1          # 声道数
PEAK_CEILING = 0.95   # 输出峰值上限（避免削波）
VOICED_RMS_DBFS = -18.0   # 浊音段目标电平

BAND_GUARD = 0.45     # 带限上限：最高谐波不超过 BAND_GUARD × Nyquist

# --------------------------------------------------------------------------
# 声带源
# --------------------------------------------------------------------------
SOURCE_METHOD = "fmfb"

# ---- 两算子 FM（备选方案，未启用）----
FM2_I = 27.0
FM2_PAIRS = 32
FM2_TILT = 2.25
FM2S_SMOOTH_OCT = 1.0 / 3.0
FM2S_TILT = 2.40

# ---- 反馈 FM ----
FM_FB_BETA = 1.0      # 反馈量。→1 时谱形趋近锯齿波（-6 dB/oct），这是起点
FM_FB_OVERSAMPLE = 4  # 过采样倍率（递归源无闭式解，抗混叠必需）

# ---- 声源提亮：高架 EQ ----
# β 只能提供约 9 dB 的亮度调节范围，不够；高频表现主要靠这条 shelf。
SOURCE_SHELF_FC = 2000.0   # 转折频率 Hz
SOURCE_SHELF_DB = 4.0     # 2kHz 以上的提升量

# 浊音输出级的高架（**在共振峰滤波器之后**）。
# 声源级的高架提到 +12dB 只换来约 +6dB —— 因为串联共振峰滤波器在高频陡降，
# 源提亮后又被滤掉了。要真正把 2~8kHz 的存在感托起来，必须在滤波之后再补一条。
VOICED_SHELF_FC = 2200.0
VOICED_SHELF_DB = 4.0

# 第二条高架，专门托起 5kHz 以上的「空气感」
VOICED_SHELF2_FC = 5000.0
VOICED_SHELF2_DB = 0.0

# ---- 4kHz 以上：明亮感的真正来源 ----
# 逐频带实测（相对本文件谱峰，dB）暴露了此前一直找错方向的证据：
#
#                0-700  700-1500 1500-2500 2500-4000 4000-6000 6000-10k 10k-20k
#   Teto /a/     -9.0     5.4     -6.7     -27.2     -16.4     -28.7   -32.7
#   我们 /a/     -8.8    -0.3      2.0     -13.4     -37.6     -48.5   -51.3
#   Teto /i/      2.8   -19.4    -27.3      -9.3      -4.1     -19.9   -24.8
#   我们 /i/      2.0   -31.0    -22.0      -8.2     -24.6     -43.9   -51.3
#
# 差别**不在 1~3kHz，而在 4kHz 以上全线低 19~26dB**；2.5~4kHz 我们反而高 14dB
# （那是 PEAK_DB=+12 延伸过去的），正是「高频很吵」的来源。所以补 2~4kHz 是
# 反的，只会更吵而不解决沉闷。
#
# 4kHz 以上要同时有两个成分：
#   * 谐波 —— 听感上是「光泽 / 金属感」，用声源高通后直接叠加
#   * 噪声 —— 听感上是「空气 / 气息」，真实录音里也有（房间声、呼吸）
# 5 级串联谐振器在 5kHz 以上是 60dB/oct 陡降，这两层都得绕过它。
HARM_AIR_HP = 4000.0       # 谐波空气的高通截止
HARM_AIR_ORDER = 4
HARM_AIR_LEVEL = 0.06      # 相对浊音段 RMS
HARM_AIR_LP = 6500.0       # 谐波空气的上限（只补 4~6.5kHz 那一段）

AIR_LEVEL = 0.013          # 噪声空气，相对浊音段 RMS
AIR_HP = 4000.0
AIR_LP = 12000.0           # 空气噪声的上限（真实录音在此之上滚降）
AIR_LP_ORDER = 2

# 共振峰旁路：把一小部分未滤波的声源直接混进输出。
# 5 级串联谐振器在 5kHz 以上是 60dB/oct 陡降，把高频**谐波**全部杀光；
# 只补噪声的话，频带能量虽然够了，但那是「嘶声」不是「光泽」——实测谐波占比
# 比 Teto 低 8~11dB。留一条旁路把谐波接回来，才是听感变亮的正解。
BYPASS_GAIN = 0.2

# 钟形均衡，用来压掉 2.5~4kHz 的多余能量（实测比 Teto 高 14dB）。
# 之前这里是 +12dB @2.2k —— 那是「高频很吵」的直接来源：Q=0.7 的钟形
# 一直延伸进 4kHz，正好落在人耳最敏感的刺耳区。
PEAK_FC = 3000.0
PEAK_DB = -8.0
PEAK_Q = 0.7

# --------------------------------------------------------------------------
# 女性化
# --------------------------------------------------------------------------
# 共振峰整体上移比例。这是「听上去像不像女声」的关键参数。
# 声学上女声共振峰通常比男声高 15~20%。
FORMANT_SCALE = 1.22

# 逐共振峰的缩放系数。
# 统一乘一个数是不对的：真实女声不是等比缩放，F1/F2 提升得多、F3 以上提升得少。
# 统一 ×1.22 把 F3 推到了 3172Hz（典型女声 /a/ 的 F3 在 2800~3000），于是
# F2(1525) 与 F3(3172) 之间留下 1647Hz 的空谷 —— 实测 1.4~2.4kHz 比 Teto
# 低 3~10dB，这才是「沉闷」的真正来源，而不是缺高频。
FORMANT_SCALE_BY_INDEX = [1.22, 1.22, 1.15, 1.10, 1.08]

# 带宽同步放大比例。带宽不该跟着共振峰等比例放大，取平方根量级更接近实际。
BANDWIDTH_SCALE = 1.35

# --------------------------------------------------------------------------
# 人性化（当前档位：轻微）
# --------------------------------------------------------------------------
# 音高不稳（jitter）：周期到周期的微小扰动，相关长度约一个声门周期。
# 这不是颤音 —— 颤音是 4~6Hz 的周期性起伏，会与 UTAU 编辑器自己加的颤音打架。
JITTER_STD = 0.003
JITTER_CORR_MS = 3.5

# 音量起伏：快一点的（shimmer）与慢一点的（自然渐弱渐强）各一条
SHIMMER_STD = 0.04
SHIMMER_CORR_MS = 25.0
AMP_DRIFT_STD = 0.05
AMP_DRIFT_CORR_MS = 60.0

# 音色漂移：每个共振峰独立地缓慢游走，模拟声道形状的微调
FORMANT_DRIFT = 0.008
FORMANT_DRIFT_CORR_MS = 80.0

# 气声：混入浊音段的宽带噪声，经声道滤波塑形
BREATH_LEVEL = 0.045
BREATH_CORR_MS = 70.0

PHASE_SEED = 20261016   # 固定种子 → 渲染结果可复现
